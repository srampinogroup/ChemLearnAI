#!/usr/bin/env python3
"""
Bond type prediction module.
Usage:
  ./bond_type_prediction.py -h
"""
import argparse
import sys

import pandas as pd
import numpy as np

try:
  import cuml.accel
  cuml.accel.install()
  print("Using cuML acceleration.", file=sys.stderr)
except ModuleNotFoundError:
  print("Not using GPU.", file=sys.stderr)

from sklearn.model_selection import train_test_split
from sklearn.model_selection import cross_val_score
from sklearn.model_selection import StratifiedKFold
from sklearn import linear_model as lm
from sklearn.preprocessing import LabelEncoder
from sklearn.ensemble import RandomForestClassifier
from sklearn import metrics as met
from xgboost import XGBClassifier

import common
import utils


# DEFAULT_IN_PATH = "../data/bonds_1-6.hdf"
# DEFAULT_OUT_DIR = "../out_bonds_1-6"
DEFAULT_IN_PATH = "../data/bonds_1-7.hdf"
DEFAULT_OUT_DIR = "../out_bonds_1-7"
DEFAULT_SHOW_FIGS = False

SCORES_CSV = "cv_scores.csv"
REPORTS_CSV = "reports.csv"

DF_SMILES = "SMILES"
DF_ATOM_INDEX = "atom index"
DF_ATOM_IX_FIRST = "0"
DF_ATOM_IX_SECOND = "1"
DF_ATOM_IX_SUM = f"{DF_ATOM_IX_FIRST}+{DF_ATOM_IX_SECOND}"
DF_BOND_TYPE = "bond type"
BOND_TYPES_ORDER = ["single", "double", "triple", "aromatic"]

RANDOM_STATE = 1
N_SPLITS = 5
VALIDATION_PROP = 0.2
MODELS = {
  "LR": lm.LogisticRegression(max_iter=10000),
  "Ri": lm.RidgeClassifier(class_weight="balanced"),
  "RF": RandomForestClassifier(
    random_state=RANDOM_STATE,
  ),
  "XGB": XGBClassifier(
    enable_categorical=True,
    tree_method="hist",
    device="gpu",
    random_state=RANDOM_STATE,
  ),
}


def parse_args() -> argparse.Namespace:
  """
  Parse command-line arguments.
  """
  parser = argparse.ArgumentParser()

  parser.add_argument(
    "-i", "--input",
    default=DEFAULT_IN_PATH,
    help=(
      "Input dataframe path. "
      f"Default is '{DEFAULT_IN_PATH}'."
    ),
  )

  parser.add_argument(
    "-o", "--out-dir",
    default=DEFAULT_OUT_DIR,
    help=(
      "Output directory path for metrics and figures. "
      f"Default is '{DEFAULT_OUT_DIR}'."
    ),
  )

  parser.add_argument(
    "-f", "--figures",
    action=argparse.BooleanOptionalAction,
    default=DEFAULT_SHOW_FIGS,
    help=(
      "Show figures generated by matplotlib during execution. "
      f"Default is {DEFAULT_SHOW_FIGS}."
    ),
  )

  return parser.parse_args()


def reshape(df: pd.DataFrame) -> pd.DataFrame:
  """
  Explode sub-arrays into proper columns.
  """
  utils.log("Reshaping dataframe...")
  for key_coeff, num_coeff in common.NUM_COEFFS.items():
    for key_atom in [DF_ATOM_IX_FIRST, DF_ATOM_IX_SECOND]:
      coeffs_cols = common.generate_coeffs_columns(
        num_coeff,
        key_coeff,
        key_atom,
      )

      old_col = f"{key_coeff} {key_atom}"

      coeffs = pd.DataFrame(
        np.column_stack(list(zip(*df[old_col]))),
        columns=coeffs_cols,
      )
      df.drop(old_col, axis=1, inplace=True)
      df = pd.concat((df, coeffs), axis=1)

    cols0 = common.generate_coeffs_columns(
      num_coeff,
      key_coeff,
      DF_ATOM_IX_FIRST,
    )
    cols1 = common.generate_coeffs_columns(
      num_coeff,
      key_coeff,
      DF_ATOM_IX_SECOND,
    )
    sum_cols = common.generate_coeffs_columns(
      num_coeff,
      key_coeff,
      DF_ATOM_IX_SUM,
    )

    for i in range(num_coeff):
      df[sum_cols[i]] = df[cols0[i]] + df[cols1[i]]

  df[DF_BOND_TYPE] = pd.Categorical(
    df[DF_BOND_TYPE], BOND_TYPES_ORDER
  )
  return df


def summarize(df: pd.DataFrame) -> None:
  """
  Print summary of the dataset.
  """
  print("Summary")
  print(f"{len(df)} CNOF bonds in total")
  print(df[DF_BOND_TYPE].value_counts())


def cv_model_coeffs(df_train: pd.DataFrame) -> pd.DataFrame:
  """
  Gather scores of models with stratified k-fold cross-validation.
  """
  utils.log("Generating cross-validation scores...")
  scores = []

  le = LabelEncoder()
  y = le.fit_transform(df_train[DF_BOND_TYPE])

  for key_model, model in MODELS.items():
    for key_coeff in common.DF_ALL_COEFFS:
      num_coeff = common.NUM_COEFFS[key_coeff]

      conc_cols = common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_FIRST
      )
      conc_cols += common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_SECOND
      )
      sum_cols = common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_SUM
      )

      features = {"concatenation": conc_cols, "sum": sum_cols}

      for key_features, x_cols in features.items():
        x = df_train[x_cols]

        skf = StratifiedKFold(
          n_splits=N_SPLITS,
          random_state=RANDOM_STATE,
          shuffle=True,
        )

        print(f"{key_model} {key_coeff} {key_features} cv")
        utils.tic(f"{key_model} {key_coeff} {key_features} cv")
        score = cross_val_score(
          model, x, y, cv=skf, scoring="f1_weighted"
        )
        _, time = utils.tac()
        print(f"f1 = {score.mean():.3f} ± {score.std():.3f}")

        scores.append([
          key_model,
          key_coeff,
          key_features,
          score.mean(),
          score.std(),
          time,
        ])

  return pd.DataFrame(scores, columns=[
    "model",
    "coeffs",
    "features",
    "f1-score avg",
    "f1-score std",
    "time (s)",
  ])


def evaluate_models(
    df_train: pd.DataFrame, df_test: pd.DataFrame, out_dir: str
) -> pd.DataFrame:
  """
  Evaluate the models on unseen data.
  """
  utils.log("Generating test reports...")
  reports = pd.DataFrame()

  le = LabelEncoder()
  y = le.fit_transform(df_train[DF_BOND_TYPE])

  for key_model, model in MODELS.items():
    for key_coeff in common.DF_ALL_COEFFS:
      num_coeff = common.NUM_COEFFS[key_coeff]

      conc_cols = common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_FIRST
      )
      conc_cols += common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_SECOND
      )
      sum_cols = common.generate_coeffs_columns(
        num_coeff, key_coeff, DF_ATOM_IX_SUM
      )

      features = {"concatenation": conc_cols, "sum": sum_cols}

      for key_features, x_cols in features.items():
        print(f"{key_model} {key_coeff} {key_features} fit and pred")
        utils.tic(f"{key_model} {key_coeff} {key_features} fit and pred")
        fitted = model.fit(df_train[x_cols], y)
        y_pred = fitted.predict(df_test[x_cols])
        y_pred = le.inverse_transform(y_pred)
        if hasattr(model, "n_iter_"):
          print(f"done in {model.n_iter_} iterations")
        utils.tac()

        report = met.classification_report(
          df_test[DF_BOND_TYPE], y_pred, output_dict=True
        )
        report = pd.DataFrame.from_dict(report)
        report["model"] = key_model
        report["coeffs"] = key_coeff
        report["features"] = key_features

        reports = pd.concat((reports, report))

        common.plot_confusion_matrix(
          df_test[DF_BOND_TYPE],
          y_pred,
          labels=BOND_TYPES_ORDER,
          title=f"{key_model} {key_coeff} {key_features}",
          out_path=(
            f"{out_dir}/cm_bondtype_"
            f"{key_model}_{key_coeff}_{key_features}.pdf"
          ),
        )

  return reports[[
    "model", "coeffs", "features",
    "single", "double", "triple", "aromatic",
    "accuracy", "macro avg", "weighted avg",
  ]]


def main() -> None:
  """
  Parse arguments and launch prediction.
  """
  utils.tic("main")
  args = parse_args()
  utils.mkdirp(args.out_dir)

  df = pd.read_hdf(args.input)
  df = reshape(df)
  summarize(df)

  df_train, df_test = train_test_split(
    df, test_size=VALIDATION_PROP, random_state=RANDOM_STATE
  )

  scores = cv_model_coeffs(df_train)
  scores.to_csv(f"{args.out_dir}/{SCORES_CSV}", index=False)
  print(scores)

  evaluation = evaluate_models(df_train, df_test, args.out_dir)
  evaluation.to_csv(
    f"{args.out_dir}/{REPORTS_CSV}", index_label="score"
  )
  print(evaluation)

  utils.tac()
  utils.log("Done.")


if __name__ == "__main__":
  main()
